export const termById = Object.fromEntries(terms.map((t) => [t.id, t]));

/** Link to the card for a term, on the lesson page that introduces it. */
export function termHref(id: string): string {
  const t = termById[id];
  if (!t) throw new Error(`Unknown term id: ${id}`);
  const base = import.meta.env.BASE_URL.replace(/\/$/, '');
  return `${base}/lessons/${t.lesson.replace('.', '-')}/#${id}`;
}
